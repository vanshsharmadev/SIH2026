export const getTenderById = (id) => {
  return mockTenders.find((t) => t.id === id || t.referenceNo === id);
};

export const filterTenders = ({ search = '', category = 'All', status = 'All' } = {}) => {
  return mockTenders.filter((tender) => {
    const matchesSearch =
      !search ||
      tender.title.toLowerCase().includes(search.toLowerCase()) ||
      tender.referenceNo.toLowerCase().includes(search.toLowerCase()) ||
      tender.ministry.toLowerCase().includes(search.toLowerCase()) ||
      tender.category.toLowerCase().includes(search.toLowerCase());

    const matchesCategory = category === 'All' || tender.category === category;
    const matchesStatus = status === 'All' || tender.status === status;

    return matchesSearch && matchesCategory && matchesStatus;
  });
};

